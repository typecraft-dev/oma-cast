#!/usr/bin/env node
// Bundles omacast's own core modules for the in-browser launcher on the site.
//   node site/build.mjs [outDir]      (default: site/public/demo)
// Writes core.js (window.OmacastCore.<Module>, the unchanged core/*.js sources) and a copy of
// data/emoji.json. Both are gitignored: run this before previewing or deploying.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(here, "..")
const out = path.resolve(process.argv[2] || path.join(here, "public/demo"))

// Only what the browser launcher uses. Each module is self-contained (CLAUDE.md), so order is free.
export const MODULES = ["Ranker", "Frecency", "OmarchyMenu", "RootSearch", "Calculator", "Emoji", "Themes", "ClipboardHistory", "Schema"]

export function bundle() {
  let js = "// Generated by site/build.mjs from core/*.js. Do not edit; edit the core modules and rebuild.\nwindow.OmacastCore = {};\n"
  for (const name of MODULES) {
    const source = fs.readFileSync(path.join(root, "core", name + ".js"), "utf8")
    js += `window.OmacastCore.${name} = (function () {\nvar module = { exports: {} };\n${source}\nreturn module.exports;\n})();\n`
  }
  return js
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(out, { recursive: true })
  fs.writeFileSync(path.join(out, "core.js"), bundle())
  fs.copyFileSync(path.join(root, "data/emoji.json"), path.join(out, "emoji.json"))
  console.log("wrote " + path.relative(process.cwd(), out) + "/core.js and emoji.json")
}
